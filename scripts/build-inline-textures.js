const fs = require("fs");
const path = require("path");

const projectRoot = path.resolve(__dirname, "..");
const textures = {
  "./assets/textures/poker/front/k.jpg": "image/jpeg",
  "./assets/textures/poker/front/j.jpg": "image/jpeg",
  "./assets/textures/poker/back/default.png": "image/png",
  "./assets/textures/mahjong/front/wan-1.png": "image/png",
  "./assets/textures/mahjong/front/east.png": "image/png",
  "./assets/textures/mahjong/back/default.jpg": "image/jpeg",
};

// 逐个读取贴图并转换成 Data URL，浏览器离线打开时才能直接使用。
function encodeTextures() {
  const encodedTextures = {};
  const texturePaths = Object.keys(textures);
  for (let index = 0; index < texturePaths.length; index += 1) {
    const relativePath = texturePaths[index];
    const mimeType = textures[relativePath];
    const sourcePath = path.join(projectRoot, relativePath.replace(/^\.\//, ""));
    const data = fs.readFileSync(sourcePath).toString("base64");
    encodedTextures[relativePath] = `data:${mimeType};base64,${data}`;
  }
  return encodedTextures;
}

const encoded = encodeTextures();

const output = `// Generated by scripts/build-inline-textures.js for file:// WebGL compatibility.\nwindow.SEAL_INLINE_TEXTURES = Object.freeze(${JSON.stringify(encoded)});\n`;
fs.writeFileSync(path.join(projectRoot, "data", "texture-inline.js"), output, "utf8");
console.log("本地 3D 贴图内嵌数据已生成：data/texture-inline.js");
